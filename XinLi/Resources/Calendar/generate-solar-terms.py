#!/usr/bin/env python3
"""Regenerate our computed solar terms; compare, but do not redistribute, HKO tables.

Python standard library only. Downloads a pinned MIT implementation, verifies its
digest before importing, then solves the apparent solar longitude for each term.
Run from any directory: python3 Resources/Calendar/generate-solar-terms.py
"""
import datetime as dt
import hashlib
import importlib.util
import json
from pathlib import Path
import tempfile
import urllib.request
import xml.etree.ElementTree as ET

COMMIT = "865d3da7d8112bbc7911238052c6af4aaf877181"
SHA256 = "41248c7b1edbf9d11119528eef7455a6dc55abde9f1aab40d363015e956c1729"
SOURCE = f"https://raw.githubusercontent.com/cosinekitty/astronomy/{COMMIT}/source/python/astronomy/astronomy.py"
HKO = "https://www.hko.gov.hk/en/gts/astronomy/data/files/24SolarTerms_{}.xml"
ROOT = Path(__file__).resolve().parents[2]
OUTPUT = Path(__file__).resolve().parent


def download(url):
    with urllib.request.urlopen(url, timeout=45) as response:
        return response.read()


def main():
    raw = download(SOURCE)
    if hashlib.sha256(raw).hexdigest() != SHA256:
        raise RuntimeError("Pinned Astronomy Engine source digest mismatch")
    rows, summaries, unix_by_year = [], [], {}
    with tempfile.TemporaryDirectory(prefix="chronocal-astronomy-") as directory:
        path = Path(directory) / "astronomy.py"
        path.write_bytes(raw)
        spec = importlib.util.spec_from_file_location("chronocal_astronomy", path)
        astronomy = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(astronomy)
        for year in range(2025, 2028):
            reference_data = download(HKO.format(year))
            official = ET.fromstring(reference_data).findall("Data")
            assert len(official) == 24
            errors, unix_by_year[year] = [], []
            for index, item in enumerate(official):
                longitude = (285 + 15 * index) % 360
                # A <= 10 day bracket is recommended by SearchSunLongitude.
                start = astronomy.Time.Make(year, index // 2 + 1, 1 if index % 2 == 0 else 15, 0, 0, 0)
                result = astronomy.SearchSunLongitude(longitude, start, 10)
                assert result is not None
                instant = result.Utc().replace(tzinfo=dt.timezone.utc)
                hour, minute = map(int, item.findtext("hm").split(":"))
                reference = dt.datetime(year, int(item.findtext("M")), int(item.findtext("D")),
                                        hour, minute, tzinfo=dt.timezone(dt.timedelta(hours=8)))
                error = abs((instant - reference).total_seconds())
                # This is comparison with a minute-rounded publication, not a
                # promise that the physical instant is known to one second.
                assert error < 60, (year, index + 1, error)
                errors.append(error)
                timestamp = round(instant.timestamp())
                unix_by_year[year].append(timestamp)
                rows.append({"year": year, "index": index + 1, "longitude": longitude,
                             "computedUTC": instant.isoformat(), "unixSeconds": timestamp})
            summaries.append({"year": year, "comparedTerms": 24, "referenceURL": HKO.format(year),
                              "referenceSHA256": hashlib.sha256(reference_data).hexdigest(),
                              "maxAbsoluteDifferenceSeconds": max(errors),
                              "meanAbsoluteDifferenceSeconds": sum(errors) / len(errors)})

    payload = {"model": "Astronomy Engine SearchSunLongitude", "commit": COMMIT,
               "sourceSHA256": SHA256, "license": "MIT", "verifiedYears": [2025, 2027],
               "referenceResolutionSeconds": 60, "comparisons": summaries, "computedTerms": rows}
    (OUTPUT / "solar-terms-computed-2025-2027.json").write_text(
        json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    lines = ["// Generated by Resources/Calendar/generate-solar-terms.py. Do not hand edit.",
             "// Computed with Astronomy Engine (MIT); see DATA-SOURCES.md and ASTRONOMY-ENGINE-LICENSE.txt.",
             "// UTC epoch seconds; only the validated 2025–2027 range is intentionally included.",
             "enum SolarTermComputedData {", "    static let unixSeconds: [Int: [Double]] = ["]
    for year, timestamps in unix_by_year.items():
        lines.append(f"        {year}: [")
        for offset in range(0, 24, 6):
            lines.append("            " + ", ".join(map(str, timestamps[offset:offset + 6])) + ",")
        lines.append("        ],")
    lines.extend(["    ]", "}", ""])
    (ROOT / "Sources/LunarCore/SolarTermComputedData.swift").write_text("\n".join(lines), encoding="utf-8")
    print(json.dumps(summaries, indent=2))


if __name__ == "__main__":
    main()
